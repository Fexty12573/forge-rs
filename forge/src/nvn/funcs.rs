//! Thin wrappers around every entry in [`NVNprocs`], named after the C function minus the `nvn` prefix.
//!
//! Each wrapper panics if NVN hasn't been initialized yet, or if the driver doesn't export that function.

use core::ffi::{c_char, c_void};

use sys::nvn::fptr::*;
use sys::nvn::types::*;

use super::procs;

macro_rules! nvn_fns {
    ($($name:ident($($arg:ident: $ty:ty),*) $(-> $ret:ty)?;)*) => {
        $(
            #[inline]
            pub unsafe fn $name($($arg: $ty),*) $(-> $ret)? {
                let f = procs().$name.expect(concat!("NVN function `", stringify!($name), "` is not available"));
                unsafe { f($($arg),*) }
            }
        )*
    };
}

